    /**
     * Get single module configuration or null if not found.
     */
    public static function getConfig(string $slug): ?array
    {
        $normalizedSlug = str_replace('_', '-', $slug);
        $map = self::getModuleMap();

        return $map[$normalizedSlug] ?? $map[$slug] ?? null;
    }

    /**
     * Get table columns with 24-hour cache.
     */
    public static function getTableColumns(string $tableName): array
    {
        return Cache::remember("schema_columns_{$tableName}", 86400, function () use ($tableName) {
            return Schema::getColumnListing($tableName);
        });
    }
